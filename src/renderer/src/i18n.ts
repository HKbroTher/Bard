const dictionaries: Record<UiLang, Record<MessageKey, string>> = { zh, en };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: UiLang): Translate {
  const dict = dictionaries[lang];
  return (key, vars) => {
    let s = dict[key] ?? zh[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export const I18nContext = createContext<{ t: Translate; lang: UiLang }>({ t: makeT("zh"), lang: "zh" });
export const useT = () => useContext(I18nContext);

/** Translate an error code from the main process (e.g. "AUTH", "NOT_FOUND: …"). */
export function errorText(t: Translate, code: string): string {
  const [head, ...rest] = code.split(":");
  const key = `error.${head}` as MessageKey;
  if (/^[A-Z_]+$/.test(head) && key in zh) return t(key) + (rest.length && rest.join(":").trim() ? ` ${rest.join(":").trim()}` : "");
  return t("error.generic", { msg: code });
}

